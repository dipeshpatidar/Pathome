CREATE TABLE staff_access_grants (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    capability VARCHAR(40) NOT NULL,
    scope_type VARCHAR(16) NOT NULL,
    city_id BIGINT,
    team_id BIGINT,
    effective_at TIMESTAMPTZ NOT NULL,
    expires_at TIMESTAMPTZ,
    revoked_at TIMESTAMPTZ,
    granted_by_user_id BIGINT,
    revoked_by_user_id BIGINT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    grant_reason_code VARCHAR(64) NOT NULL,
    revoke_reason_code VARCHAR(64),
    provisioning_source VARCHAR(32) NOT NULL,
    CONSTRAINT fk_staff_grants_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_staff_grants_city FOREIGN KEY (city_id) REFERENCES supported_cities (id),
    CONSTRAINT fk_staff_grants_team FOREIGN KEY (team_id) REFERENCES operating_teams (id),
    CONSTRAINT fk_staff_grants_grantor FOREIGN KEY (granted_by_user_id) REFERENCES users (id),
    CONSTRAINT fk_staff_grants_revoker FOREIGN KEY (revoked_by_user_id) REFERENCES users (id),
    CONSTRAINT ck_staff_grants_capability CHECK (capability IN (
        'STAFF_ADMIN', 'CITY_TEAM_ADMIN', 'OPS_INTAKE', 'OPS_COORDINATE', 'OPS_SUPERVISE'
    )),
    CONSTRAINT ck_staff_grants_scope_type CHECK (scope_type IN ('GLOBAL', 'CITY', 'TEAM')),
    CONSTRAINT ck_staff_grants_scope_shape CHECK (
        (scope_type = 'GLOBAL' AND city_id IS NULL AND team_id IS NULL)
        OR (scope_type = 'CITY' AND city_id IS NOT NULL AND team_id IS NULL)
        OR (scope_type = 'TEAM' AND city_id IS NULL AND team_id IS NOT NULL)
    ),
    CONSTRAINT ck_staff_grants_capability_scope CHECK (
        (capability = 'STAFF_ADMIN' AND scope_type = 'GLOBAL')
        OR (capability = 'CITY_TEAM_ADMIN' AND scope_type = 'CITY')
        OR (capability = 'OPS_INTAKE' AND scope_type = 'CITY')
        OR (capability IN ('OPS_COORDINATE', 'OPS_SUPERVISE') AND scope_type = 'TEAM')
    ),
    CONSTRAINT ck_staff_grants_interval CHECK (expires_at IS NULL OR expires_at > effective_at),
    CONSTRAINT ck_staff_grants_admin_no_expiry CHECK (capability <> 'STAFF_ADMIN' OR expires_at IS NULL),
    CONSTRAINT ck_staff_grants_revocation_shape CHECK (
        (revoked_at IS NULL AND revoked_by_user_id IS NULL AND revoke_reason_code IS NULL)
        OR (revoked_at IS NOT NULL AND revoke_reason_code IS NOT NULL)
    ),
    CONSTRAINT ck_staff_grants_reason CHECK (grant_reason_code ~ '^[A-Z][A-Z0-9_]{0,63}$'),
    CONSTRAINT ck_staff_grants_revoke_reason CHECK (
        revoke_reason_code IS NULL OR revoke_reason_code ~ '^[A-Z][A-Z0-9_]{0,63}$'
    ),
    CONSTRAINT ck_staff_grants_provisioning_source CHECK (
        provisioning_source IN ('ADMIN_API', 'INITIAL_BOOTSTRAP', 'OPERATOR_RECOVERY')
    )
);

CREATE INDEX idx_staff_grants_user_cap_effective
