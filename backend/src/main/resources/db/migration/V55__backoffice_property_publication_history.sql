ALTER TABLE listings
    ADD COLUMN last_content_published_at TIMESTAMP,
    ADD COLUMN title_provenance VARCHAR(24);

ALTER TABLE property_upload_drafts
    ADD COLUMN staff_maker_user_id BIGINT,
    ADD COLUMN revision_mode VARCHAR(32);

ALTER TABLE property_upload_drafts
    ADD CONSTRAINT fk_pud_staff_maker
    FOREIGN KEY (staff_maker_user_id) REFERENCES users(id) ON DELETE RESTRICT;

ALTER TABLE property_draft_media
    ADD COLUMN source_media_asset_id BIGINT,
    ADD COLUMN caption VARCHAR(255);

ALTER TABLE property_draft_media
    ADD CONSTRAINT fk_pdm_source_media_asset
    FOREIGN KEY (source_media_asset_id) REFERENCES property_media_assets(id) ON DELETE RESTRICT;

ALTER TABLE property_media_assets
    ADD COLUMN retired_at TIMESTAMP;

CREATE INDEX idx_property_media_current_listing
    ON property_media_assets (listing_id, sort_order, id)
    WHERE retired_at IS NULL;

CREATE TABLE property_publication_versions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    listing_id BIGINT NOT NULL REFERENCES listings(id) ON DELETE RESTRICT,
    publication_version BIGINT NOT NULL CHECK (publication_version > 0),
    revision_id VARCHAR(64) NOT NULL,
    event_kind VARCHAR(32) NOT NULL,
    actor_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    authority_evidence JSONB NOT NULL,
    before_snapshot JSONB,
    after_snapshot JSONB NOT NULL,
    changed_fields JSONB NOT NULL,
    published_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uk_publication_listing_version UNIQUE (listing_id, publication_version),
    CONSTRAINT uk_publication_revision UNIQUE (listing_id, revision_id)
);

CREATE INDEX idx_publication_listing_time
    ON property_publication_versions (listing_id, publication_version DESC);

CREATE TABLE property_revision_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    listing_id BIGINT NOT NULL REFERENCES listings(id) ON DELETE RESTRICT,
    draft_id VARCHAR(64),
    event_type VARCHAR(40) NOT NULL,
    actor_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    occurred_at TIMESTAMPTZ NOT NULL,
    draft_version INTEGER,
    details JSONB NOT NULL
);

CREATE INDEX idx_property_revision_events_listing_time
    ON property_revision_events (listing_id, occurred_at DESC, id DESC);

CREATE TABLE property_command_receipts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    operation_id UUID NOT NULL UNIQUE,
    command_type VARCHAR(40) NOT NULL,
    aggregate_id BIGINT NOT NULL,
    payload_hash VARCHAR(64) NOT NULL,
    actor_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    result_version BIGINT,
    created_at TIMESTAMPTZ NOT NULL
);

CREATE INDEX idx_property_command_receipt_aggregate
    ON property_command_receipts (aggregate_id, command_type, created_at DESC);

CREATE TABLE property_publication_outbox (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    listing_id BIGINT NOT NULL REFERENCES listings(id) ON DELETE RESTRICT,
    publication_version BIGINT NOT NULL,
    event_type VARCHAR(40) NOT NULL,
    payload JSONB NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    dispatched_at TIMESTAMPTZ,
    CONSTRAINT uk_publication_outbox_version UNIQUE (listing_id, publication_version)
);

CREATE INDEX idx_publication_outbox_pending
    ON property_publication_outbox (created_at, id)
    WHERE dispatched_at IS NULL;

CREATE OR REPLACE FUNCTION reject_property_history_rewrite()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    RAISE EXCEPTION 'Property publication and command history is immutable';
END;
$$;

CREATE TRIGGER property_publication_versions_immutable
    BEFORE UPDATE OR DELETE ON property_publication_versions
    FOR EACH ROW EXECUTE FUNCTION reject_property_history_rewrite();

CREATE TRIGGER property_command_receipts_immutable
    BEFORE UPDATE OR DELETE ON property_command_receipts
    FOR EACH ROW EXECUTE FUNCTION reject_property_history_rewrite();

CREATE TRIGGER property_revision_events_immutable
    BEFORE UPDATE OR DELETE ON property_revision_events
    FOR EACH ROW EXECUTE FUNCTION reject_property_history_rewrite();

