CREATE INDEX idx_team_locality_coverage_active_locality
    ON team_locality_coverage (supported_city_id, canonical_locality_id, operating_team_id)
    WHERE active = TRUE;

CREATE FUNCTION protect_team_locality_coverage_history() RETURNS trigger AS $$
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION 'Team locality coverage history cannot be deleted';
    END IF;
    IF (NEW.supported_city_id, NEW.canonical_locality_id, NEW.operating_team_id,
        NEW.created_at, NEW.created_by_user_id)
       IS DISTINCT FROM
       (OLD.supported_city_id, OLD.canonical_locality_id, OLD.operating_team_id,
        OLD.created_at, OLD.created_by_user_id) THEN
        RAISE EXCEPTION 'Team locality coverage identity is immutable';
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_team_locality_coverage_history
    BEFORE UPDATE OR DELETE ON team_locality_coverage
    FOR EACH ROW EXECUTE FUNCTION protect_team_locality_coverage_history();

CREATE TABLE visit_request_routing_tasks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id BIGINT NOT NULL,
    provenance VARCHAR(40) NOT NULL,
    protocol_version INTEGER NOT NULL,
    state VARCHAR(24) NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    expected_request_version BIGINT NOT NULL,
    attempts INTEGER NOT NULL DEFAULT 0,
    available_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    enrolled_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    completed_at TIMESTAMPTZ,
    last_error_code VARCHAR(64),
    decision_code VARCHAR(64),
    coverage_id BIGINT,
    coverage_version BIGINT,
    result_team_id BIGINT,
    result_request_version BIGINT,
    audit_event_id BIGINT,
    CONSTRAINT fk_visit_request_routing_task_request
        FOREIGN KEY (request_id) REFERENCES property_visit_requests (id),
    CONSTRAINT fk_visit_request_routing_task_coverage
        FOREIGN KEY (coverage_id) REFERENCES team_locality_coverage (id),
    CONSTRAINT fk_visit_request_routing_task_team
        FOREIGN KEY (result_team_id) REFERENCES operating_teams (id),
    CONSTRAINT fk_visit_request_routing_task_audit
        FOREIGN KEY (audit_event_id) REFERENCES operational_audit_events (id),
    CONSTRAINT uk_visit_request_routing_task_request UNIQUE (request_id),
    CONSTRAINT ck_visit_request_routing_task_provenance
        CHECK (provenance = 'TRUSTED_NEW_REQUEST_V1'),
    CONSTRAINT ck_visit_request_routing_task_protocol CHECK (protocol_version > 0),
    CONSTRAINT ck_visit_request_routing_task_state CHECK (
        state IN ('PENDING', 'RETRY', 'NEEDS_REVIEW', 'DONE', 'SKIPPED')
    ),
    CONSTRAINT ck_visit_request_routing_task_version CHECK (version >= 0),
    CONSTRAINT ck_visit_request_routing_task_request_version CHECK (expected_request_version >= 0),
    CONSTRAINT ck_visit_request_routing_task_attempts CHECK (attempts >= 0),
    CONSTRAINT ck_visit_request_routing_task_error
        CHECK (last_error_code IS NULL OR last_error_code ~ '^[A-Z][A-Z0-9_]{0,63}$'),
    CONSTRAINT ck_visit_request_routing_task_decision
        CHECK (decision_code IS NULL OR decision_code ~ '^[A-Z][A-Z0-9_]{0,63}$'),
    CONSTRAINT ck_visit_request_routing_task_result_shape CHECK (
        (result_team_id IS NULL AND result_request_version IS NULL AND audit_event_id IS NULL)
        OR (result_team_id IS NOT NULL AND result_request_version IS NOT NULL AND audit_event_id IS NOT NULL)
    ),
    CONSTRAINT ck_visit_request_routing_task_completion CHECK (
        (state = 'DONE' AND completed_at IS NOT NULL AND result_team_id IS NOT NULL)
        OR (state <> 'DONE' AND completed_at IS NULL)
    )
);

CREATE INDEX idx_visit_request_routing_task_due
    ON visit_request_routing_tasks (available_at, id)
    WHERE state IN ('PENDING', 'RETRY');
CREATE INDEX idx_visit_request_routing_task_review
    ON visit_request_routing_tasks (updated_at, id)
    WHERE state = 'NEEDS_REVIEW';
