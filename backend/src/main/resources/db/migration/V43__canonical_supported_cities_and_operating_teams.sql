WITH unambiguous_locality_cities AS (
    SELECT l.id AS locality_id, MIN(c.id) AS supported_city_id
    FROM localities l
    JOIN supported_cities c
      ON lower(btrim(l.city)) = lower(btrim(c.display_name))
    GROUP BY l.id
    HAVING COUNT(*) = 1
)
UPDATE localities l
SET supported_city_id = mapped.supported_city_id
FROM unambiguous_locality_cities mapped
WHERE l.id = mapped.locality_id;
