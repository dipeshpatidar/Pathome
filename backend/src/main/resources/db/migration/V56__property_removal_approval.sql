-- Approved Property Removal A-E additive source contract.
-- Authored only. No migration is executed by this package.

CREATE TABLE property_removal_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    listing_id BIGINT NOT NULL REFERENCES listings(id) ON DELETE RESTRICT,
    requester_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
    request_status VARCHAR(16) NOT NULL CHECK (
        request_status IN ('PENDING', 'APPROVED', 'REJECTED', 'WITHDRAWN')
    ),
    request_version BIGINT NOT NULL DEFAULT 0 CHECK (request_version >= 0),
    creation_operation_id UUID NOT NULL,
    creation_payload_hash VARCHAR(64) NOT NULL,
    requested_at TIMESTAMPTZ NOT NULL,
    requested_listing_version BIGINT NOT NULL CHECK (requested_listing_version >= 0),
    owner_reason VARCHAR(1000),
    terminal_operation_id UUID,
    terminal_payload_hash VARCHAR(64),
    decision_actor_user_id BIGINT REFERENCES users(id) ON DELETE RESTRICT,
    decided_at TIMESTAMPTZ,
    decision_reason VARCHAR(1000),
    observed_listing_version BIGINT,
    resulting_listing_version BIGINT,
    authority_evidence JSONB,
    CONSTRAINT uk_removal_creation_operation UNIQUE (requester_user_id, creation_operation_id),
    CONSTRAINT uk_removal_terminal_operation UNIQUE (terminal_operation_id),
    CONSTRAINT chk_removal_reason_length CHECK (
        owner_reason IS NULL OR char_length(btrim(owner_reason)) BETWEEN 1 AND 1000
    ),
    CONSTRAINT chk_removal_terminal_shape CHECK (
        (request_status = 'PENDING'
            AND terminal_operation_id IS NULL
            AND terminal_payload_hash IS NULL
            AND decided_at IS NULL
            AND decision_actor_user_id IS NULL
            AND resulting_listing_version IS NULL)
        OR
        (request_status = 'WITHDRAWN'
            AND terminal_operation_id IS NOT NULL
            AND terminal_payload_hash IS NOT NULL
            AND decided_at IS NOT NULL
            AND decision_actor_user_id = requester_user_id
            AND resulting_listing_version = observed_listing_version)
        OR
        (request_status IN ('APPROVED', 'REJECTED')
            AND terminal_operation_id IS NOT NULL
            AND terminal_payload_hash IS NOT NULL
            AND decided_at IS NOT NULL
            AND decision_actor_user_id IS NOT NULL
            AND decision_reason IS NOT NULL
            AND char_length(btrim(decision_reason)) BETWEEN 1 AND 1000
            AND observed_listing_version IS NOT NULL
            AND resulting_listing_version IS NOT NULL)
    )
);

CREATE UNIQUE INDEX uk_removal_one_pending_per_listing
    ON property_removal_requests (listing_id)
    WHERE request_status = 'PENDING';

CREATE INDEX idx_removal_admin_queue
    ON property_removal_requests (request_status, requested_at DESC, id DESC);

CREATE INDEX idx_removal_owner_history
    ON property_removal_requests (requester_user_id, requested_at DESC, id DESC);

CREATE INDEX idx_removal_listing_history
    ON property_removal_requests (listing_id, requested_at DESC, id DESC);

CREATE OR REPLACE FUNCTION guard_property_removal_request_transition()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION 'Property removal requests are historical records and cannot be deleted';
    END IF;

    IF OLD.request_status <> 'PENDING' THEN
        RAISE EXCEPTION 'A terminal property removal request is immutable';
    END IF;

    IF NEW.listing_id <> OLD.listing_id
       OR NEW.requester_user_id <> OLD.requester_user_id
       OR NEW.creation_operation_id <> OLD.creation_operation_id
       OR NEW.creation_payload_hash <> OLD.creation_payload_hash
       OR NEW.requested_at <> OLD.requested_at
       OR NEW.requested_listing_version <> OLD.requested_listing_version
       OR NEW.owner_reason IS DISTINCT FROM OLD.owner_reason THEN
        RAISE EXCEPTION 'Property removal request creation facts are immutable';
    END IF;

    IF NEW.request_status NOT IN ('APPROVED', 'REJECTED', 'WITHDRAWN') THEN
        RAISE EXCEPTION 'Property removal request can only transition to a terminal state';
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER property_removal_request_transition_guard
    BEFORE UPDATE OR DELETE ON property_removal_requests
    FOR EACH ROW EXECUTE FUNCTION guard_property_removal_request_transition();

